// The profiles the onboarding advises from (odd/tasks/onboarding.md, D9): global areas, the kinds of project, and
// the bar targets each kind measures. This file is data and imports nothing; bin/lib/profiles.mjs reads it and
// `js-harness onboard profile` prints it one piece at a time, so it is never loaded into a session whole.
//
// Tool and library names are starting points the session checks against current docs and release notes before it
// recommends them (D12); versions are left out on purpose. An area's `default` and `alternatives` are its advice for
// a kind that names no advice of its own; a kind's entry for an area overrides them. A target's `source` is a URL
// or AGREED, never a bare number, and its `measured` says where: `lab` (CI, before release), `field` (real users,
// in production) or `review` (a checklist read before a release).

